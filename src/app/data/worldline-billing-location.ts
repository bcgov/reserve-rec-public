export interface WorldlineBillingLocation {
  province: string;
  country: string;
}

export function toWorldlineBillingLocation(
  province: string,
  country: string,
): WorldlineBillingLocation {
  const normalizedCountry = country.trim().toLowerCase();
  const normalizedProvince = province.trim().toLowerCase();
  const countryCode = COUNTRY_CODES[normalizedCountry];

  if (countryCode === 'CA') {
    return {
      province: CANADIAN_PROVINCE_CODES[normalizedProvince] || province.trim(),
      country: countryCode,
    };
  }

  if (countryCode === 'US') {
    return {
      province: US_STATE_CODES[normalizedProvince] || province.trim(),
      country: countryCode,
    };
  }

  return { province: province.trim(), country: country.trim() };
}
